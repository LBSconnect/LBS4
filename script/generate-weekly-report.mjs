#!/usr/bin/env node
// Assembles the dated weekly site-health report from whatever artifacts the
// workflow produced this run (crawl JSON, npm audit JSON, git diff, risk
// classification). Designed to degrade gracefully — a missing artifact
// (e.g. the crawl step failed entirely) becomes a "not available this run"
// line in the report instead of crashing the whole workflow.
//
// Usage:
//   node script/generate-weekly-report.mjs --date 2026-08-14 \
//     --baseline-sha <sha> --production-url https://www.lbs4.com \
//     --out reports/site-health/2026-08-14/report.md

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 ? process.argv[i + 1] : fallback;
}

function readJsonSafe(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function sh(cmd, fallback = "") {
  try {
    return execSync(cmd, { encoding: "utf8" }).trim();
  } catch {
    return fallback;
  }
}

const date = arg("date", new Date().toISOString().slice(0, 10));
const baselineSha = arg("baseline-sha", "unknown");
const productionUrl = arg("production-url", "https://www.lbs4.com");
const outPath = arg("out", `reports/site-health/${date}/report.md`);

const crawl = readJsonSafe("reports/crawl-report.json");
const npmAudit = readJsonSafe("reports/npm-audit.json");
const currentSha = sh("git rev-parse HEAD", "unknown");
const changedFiles = sh("git diff --name-only " + baselineSha + " -- .", "").split("\n").filter(Boolean);

const npmAuditSummary = npmAudit?.metadata?.vulnerabilities
  ? Object.entries(npmAudit.metadata.vulnerabilities)
      .filter(([, count]) => count > 0)
      .map(([sev, count]) => `${count} ${sev}`)
      .join(", ") || "none reported"
  : "not available this run";

const lines = [];
lines.push(`# Weekly Site Health Report — ${date}`);
lines.push("");
lines.push(`- **Production URL tested:** ${productionUrl}`);
lines.push(`- **Baseline commit:** \`${baselineSha}\``);
lines.push(`- **Commit tested this run:** \`${currentSha}\``);
lines.push(`- **Run started (UTC):** ${new Date().toISOString()}`);
lines.push("");
lines.push("## Crawl Results");
if (crawl) {
  lines.push(`- Pages crawled: ${crawl.pagesCrawled}${crawl.cappedAtMax ? " (hit crawl cap — site may have more pages than this)" : ""}`);
  lines.push(`- Broken links/pages (4xx/5xx or fetch error): ${crawl.brokenCount}`);
  lines.push(`- Redirects encountered: ${crawl.redirectCount}`);
  if (crawl.brokenCount > 0) {
    lines.push("");
    lines.push("| URL | Status | Error |");
    lines.push("|---|---|---|");
    for (const b of crawl.broken.slice(0, 30)) {
      lines.push(`| ${b.url} | ${b.status ?? "-"} | ${b.error ?? "-"} |`);
    }
    if (crawl.broken.length > 30) lines.push(`| ...and ${crawl.broken.length - 30} more | | |`);
  }
} else {
  lines.push("- Not available this run (crawl step did not produce a report).");
}
lines.push("");
lines.push("## Dependency / Security Audit");
lines.push(`- \`npm audit\`: ${npmAuditSummary}`);
lines.push("");
lines.push("## Files Changed This Run");
if (changedFiles.length > 0) {
  lines.push(...changedFiles.map((f) => `- \`${f}\``));
} else {
  lines.push("- No files changed relative to baseline.");
}
lines.push("");
lines.push("## Notes");
lines.push("- This report is generated by `.github/workflows/weekly-site-health.yml`. See `WEEKLY_SITE_HEALTH.md` in the repo root for how the schedule, auto-merge rules, and notifications work, and what secrets need to be configured.");
lines.push("- No secrets, tokens, or personal/customer data are included in this report by design.");
lines.push("");

writeFileSync(outPath, lines.join("\n"));
console.log(`Report written to ${outPath}`);
